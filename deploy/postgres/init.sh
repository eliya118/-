#!/bin/bash
set -euo pipefail

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname postgres <<SQL
CREATE USER calendar_app WITH PASSWORD '${CALENDAR_DB_PASSWORD}';
CREATE USER ideas_app WITH PASSWORD '${IDEAS_DB_PASSWORD}';
CREATE USER notifier_app WITH PASSWORD '${NOTIFIER_DB_PASSWORD}';
CREATE DATABASE calendar OWNER calendar_app;
CREATE DATABASE ideas OWNER ideas_app;
CREATE DATABASE notifier OWNER notifier_app;
REVOKE CONNECT ON DATABASE postgres FROM PUBLIC;
GRANT CONNECT ON DATABASE postgres TO ${POSTGRES_USER};
REVOKE ALL ON DATABASE calendar FROM PUBLIC;
REVOKE ALL ON DATABASE ideas FROM PUBLIC;
REVOKE ALL ON DATABASE notifier FROM PUBLIC;
GRANT CONNECT ON DATABASE calendar TO calendar_app;
GRANT CONNECT ON DATABASE ideas TO ideas_app;
GRANT CONNECT ON DATABASE notifier TO notifier_app;
SQL
